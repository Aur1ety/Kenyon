#!/usr/bin/env node
// Copies the stored result files the website cites from ../results into public/data/results, and the video from
// ../media/mb_memory.mp4 into public/media, byte for byte.
//
// The site quotes these files (the ten-draw spreads, the recurrent-model body effect, the negatives) rather than
// typing their numbers into the page, and it must build on its own (Vercel's Root Directory is web/), so it
// ships verbatim copies. tests/results.test.js fails if a copy drifts from the file in results/ or media/.
//
//   node scripts/sync_results.mjs          (or: npm run sync-results)

import { copyFileSync, existsSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { RESULT_FILES } from '../src/ui/resultFiles.js';

const here = dirname(fileURLToPath(import.meta.url));
const src = join(here, '..', '..', 'results');
const dst = join(here, '..', 'public', 'data', 'results');

if (!existsSync(src)) {
  console.error(`no results directory at ${src}`);
  process.exit(1);
}
mkdirSync(dst, { recursive: true });
for (const f of Object.values(RESULT_FILES)) {
  copyFileSync(join(src, f), join(dst, f));
  console.log(`copied results/${f}`);
}

// the video (regenerated by `python -m kenyon.viz.video --out media/mb_memory.mp4`)
const video = join(here, '..', '..', 'media', 'mb_memory.mp4');
if (existsSync(video)) {
  const mediaDst = join(here, '..', 'public', 'media');
  mkdirSync(mediaDst, { recursive: true });
  copyFileSync(video, join(mediaDst, 'mb_memory.mp4'));
  console.log('copied media/mb_memory.mp4');
} else {
  console.warn(`no video at ${video}; public/media/mb_memory.mp4 left as it is`);
}
